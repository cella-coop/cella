CREATE SCHEMA membership_project;

-- A share of a project's budget granted to a member: a right to spend up
-- to its amount for the project, on suppliers, print or freelance work.
-- Shares add up per member; together they never exceed the budget.
CREATE TABLE membership_project.share (
  circle text NOT NULL DEFAULT circle.assembly() REFERENCES circle.circle,
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project text NOT NULL,
  member text NOT NULL,
  amount cella.amount NOT NULL,
  granted date NOT NULL
);

CREATE INDEX ON membership_project.share (project);

-- A share goes to an active member, from a live project's budget, and
-- within what is left of it. The project's row is locked for the check,
-- so two shares granted at once are counted one after the other, and a
-- budget set at the same time waits for them.
CREATE FUNCTION membership_project.within() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  budget bigint;
  archived date;
  shared bigint;
BEGIN
  IF NOT EXISTS (SELECT FROM membership.member m WHERE m.address = NEW.member AND m.status = 'active') THEN
    RAISE EXCEPTION '% is no active member', NEW.member USING ERRCODE = 'triggered_action_exception';
  END IF;
  SELECT cella.cents(p.budget), p.archived INTO budget, archived FROM project.project p WHERE p.id = NEW.project FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'no project %', NEW.project USING ERRCODE = 'triggered_action_exception';
  END IF;
  IF archived IS NOT NULL THEN
    RAISE EXCEPTION '% was archived on %', NEW.project, archived USING ERRCODE = 'triggered_action_exception';
  END IF;
  IF budget IS NULL THEN
    RAISE EXCEPTION '% has no budget to share', NEW.project USING ERRCODE = 'triggered_action_exception';
  END IF;
  SELECT coalesce(sum(cella.cents(s.amount)), 0) INTO shared FROM membership_project.share s WHERE s.project = NEW.project;
  IF shared + cella.cents(NEW.amount) > budget THEN
    RAISE EXCEPTION 'a share of % cents exceeds what is left of %''s budget, % of % cents',
      cella.cents(NEW.amount), NEW.project, budget - shared, budget
      USING ERRCODE = 'triggered_action_exception';
  END IF;
  RETURN NEW;
END
$$;

CREATE TRIGGER within BEFORE INSERT ON membership_project.share
  FOR EACH ROW EXECUTE FUNCTION membership_project.within();

-- What each project's budget has shared out, and what is left of it, in
-- cents.
CREATE VIEW membership_project.pot WITH (security_invoker = true) AS
SELECT p.id AS project, cella.cents(p.budget) AS budget,
       coalesce(sum(cella.cents(s.amount)), 0)::bigint AS shared,
       (cella.cents(p.budget) - coalesce(sum(cella.cents(s.amount)), 0))::bigint AS remaining
FROM project.project p
LEFT JOIN membership_project.share s ON s.project = p.id
GROUP BY p.id, p.budget;

-- project:project:budget — the budget still covers every share granted
-- from it.
CREATE FUNCTION membership_project.covers(payload jsonb) RETURNS text
LANGUAGE sql STABLE
BEGIN ATOMIC
  SELECT CASE
    WHEN t.shared > t.budget THEN t.project || '''s shares come to ' || t.shared::text || ' cents, more than a budget of ' || t.budget::text
  END
  FROM membership_project.pot t
  WHERE t.project = payload ->> 'project';
END;

INSERT INTO cella.guard (op, fn, owner) VALUES ('project:project:budget', 'membership_project.covers(jsonb)', 'membership-project');

GRANT USAGE ON SCHEMA membership_project TO cella_app, cella_guards;
GRANT SELECT, INSERT ON membership_project.share TO cella_app;
GRANT SELECT ON membership_project.pot TO cella_app;
GRANT SELECT ON membership_project.share, membership_project.pot TO cella_guards;
