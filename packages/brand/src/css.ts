// The files the brand ships, written from the model: tokens.css and
// tokens.json, fonts.css, starlight.css and the icons. tokens.css composes
// the roles as the explorer's :root rules do, from shades the theme
// mirrors, so dark mode is one variable and any element with a data-theme
// wears that theme.

import { hex, type Oklch } from './color.ts'
import { hues, inkAction, PENTAD, TONES, type Face, type House } from './house.ts'
import { grain, SURFACES } from './paper.ts'
import { compressed, inks, K, ROLES, role, rung, shades, sunkL, sunkRung, onActionL, type Role, type Theme } from './tones.ts'

const n = (v: number, d = 4): string => String(+v.toFixed(d))
const ok = ([l, c, h]: Oklch): string => `oklch(${n(l)} ${n(c)} ${n(h, 2)})`

export const HEADER = '/* Generated by `cella brand` from house.json; change house.json, then run it. */\n'

/** The type scale's steps, from the base by the ratio. */
export const STEPS = { xs: -2, sm: -1, md: 0, lg: 1, xl: 2, '2xl': 3, '3xl': 4, '4xl': 5 } as const

/** Fontsource's variable build of a family, the package the brand takes
    it from. */
export const fontPackage = (family: string): string => `@fontsource-variable/${family.toLowerCase().replace(/ /g, '-')}`

const ROLES_TYPE = ['display', 'text', 'mono'] as const

function stack(role: (typeof ROLES_TYPE)[number], face: Face): string {
  const fallback = role === 'mono' ? 'ui-monospace, monospace' : 'system-ui, sans-serif'
  return `'${face.family} Variable', '${face.family}', ${fallback}`
}

function fvs(face: Face): string {
  const parts = Object.entries(face.axes)
    .filter(([tag]) => tag !== 'wght')
    .map(([tag, v]) => `'${tag}' ${v}`)
  return parts.length ? parts.join(', ') : 'normal'
}

function roleCss(house: House, r: Role): string {
  const l = r.l === 'sunk' ? 'var(--sunk-l)' : r.l === 'action' ? 'var(--accent-l)' : r.l === 'on-action' ? (inkAction(house) ? 'var(--shade-0)' : n(onActionL(house, 1))) : `var(--shade-${r.l})`
  const a = r.alpha === 'hover' ? ' / 60%' : r.alpha === 'soft' ? ' / var(--soft-a)' : r.alpha === 'accent-soft' ? ' / var(--accent-soft-a)' : ''
  return `oklch(${l} var(--tone-${r.tone})${a})`
}

const block = (selector: string, lines: string[]): string => `${selector} {\n${lines.map((l) => `  ${l}`).join('\n')}\n}\n`
const media = (inner: string): string => `@media (prefers-color-scheme: dark) {\n${inner.replace(/^(?=.)/gm, '  ')}}\n`

/** What differs in dark beyond the sign: the compressed surfaces and the
    paper. */
function darkLines(house: House): string[] {
  const dark = shades(house, -1)
  return [
    ...K.map((_, i) => i).filter((i) => compressed(house, i)).map((i) => `--shade-${i}: ${n(dark[i])};`),
    ...SURFACES.map((s) => `--grain-${s}: ${grain(house, s, -1)};`),
  ]
}

export function tokensCss(house: House): string {
  const hs = hues(house)
  const theme = [
    '/* The theme: one sign, light by default, dark where the system',
    '   prefers it, and either where an element says data-theme. */',
    block(':root, [data-theme=\'light\']', ['--theme: 1;', 'color-scheme: light;']),
    media(block(':root:not([data-theme=\'light\'])', ['--theme: -1;', 'color-scheme: dark;'])),
    block('[data-theme=\'dark\']', ['--theme: -1;', 'color-scheme: dark;']),
  ]
  const type = ROLES_TYPE.flatMap((r) => {
    const face = house.fonts[r]
    return [`--font-${r}: ${stack(r, face)};`, `--fw-${r}: ${face.axes.wght ?? 400};`, `--fvs-${r}: ${fvs(face)};`]
  })
  const { base, ratio, leading, track } = house.scale
  const constants = [
    '/* Tones: a chroma and a hue. The paper is graphite; the accent is the',
    '   paper\'s, since an action is ink; the five states are the brand. */',
    ...TONES.map((t) => `--tone-${t}: ${n(house.tones[t].c)} ${n(house.tones[t].h, 2)};`),
    '/* The five inks, in the pentad\'s order: error, warning, success,',
    '   info, help. */',
    ...inks(house, hs).map((c, i) => `--p${i}: ${ok(c)};`),
    '/* Type. */',
    ...type,
    ...Object.entries(STEPS).map(([k, s]) => `--t-${k}: ${(base * ratio ** s).toFixed(2)}px;`),
    `--leading: ${leading};`,
    `--track-display: ${track}em;`,
    `--grain-blend: ${house.paper.blend};`,
    '/* Shape. */',
    '--radius: 12px;',
    '--radius-control: 6px;',
    '--ease: cubic-bezier(0.2, 0, 0, 1);',
    '--shadow-float: 0 2px 6px oklch(0.2 0.02 60 / 10%), 0 16px 40px oklch(0.2 0.02 60 / 16%);',
  ]
  const model = [
    '/* Shades: a lightness around the midpoint, mirrored by --theme. */',
    ...K.map((_, i) => `--shade-${i}: calc(${n(house.mid)} + var(--theme) * ${n(house.contrast * rung(house, i))});`),
    `--sunk-l: calc(${n(house.mid)} + var(--theme) * ${n(house.contrast * sunkRung(house))});`,
    `--accent-l: ${inkAction(house) ? 'var(--shade-9)' : n(house.accentL)};`,
    '--soft-a: calc(0.46 + var(--theme) * 0.14);',
    '--accent-soft-a: calc(0.4 + var(--theme) * 0.15);',
    '/* The paper each surface wears, as background-image. */',
    ...SURFACES.map((s) => `--grain-${s}: ${grain(house, s, 1)};`),
    '/* Roles: what components read, never a shade. */',
    ...Object.entries(ROLES).map(([name, r]) => `--${name}: ${roleCss(house, r)};`),
  ]
  return [
    HEADER,
    ...theme,
    block(':root', constants),
    '/* Declared on every [data-theme] as well, so a region can wear the',
    '   other theme. */',
    block(':root, [data-theme]', model),
    '/* An equal step in lightness reads stronger near black, so dark',
    '   compresses its surfaces, and wears the paper at a fraction. */',
    media(block(':root:not([data-theme=\'light\'])', darkLines(house))),
    block('[data-theme=\'dark\']', darkLines(house)),
  ].join('\n')
}

/** The same values for code, in both themes. */
export function tokensJson(house: House): string {
  const hs = hues(house)
  const theme = (t: Theme) => ({
    shades: shades(house, t).map((l) => n(l)).map(Number),
    sunk: Number(n(sunkL(house, t))),
    roles: Object.fromEntries(Object.keys(ROLES).map((name) => {
      const { oklch, alpha } = role(house, name, t)
      return [name, { oklch: ok(oklch), hex: hex(oklch), alpha: Number(n(alpha, 3)) }]
    })),
  })
  const { base, ratio, leading, track } = house.scale
  return `${JSON.stringify({
    hues: Object.fromEntries(PENTAD.map((k, i) => [k, hs[i]])),
    inks: Object.fromEntries(PENTAD.map((k, i) => {
      const c = inks(house, hs)[i]
      return [k, { oklch: ok(c), hex: hex(c) }]
    })),
    light: theme(1),
    dark: theme(-1),
    type: {
      ...Object.fromEntries(ROLES_TYPE.map((r) => [r, { family: house.fonts[r].family, package: fontPackage(house.fonts[r].family), stack: stack(r, house.fonts[r]), axes: house.fonts[r].axes }])),
      scale: Object.fromEntries(Object.entries(STEPS).map(([k, s]) => [k, Number((base * ratio ** s).toFixed(2))])),
      leading,
      track,
    },
    mark: house.mark,
  }, null, 2)}\n`
}

/** The three faces, from Fontsource's variable builds. */
export function fontsCss(house: House): string {
  const pkgs = [...new Set(ROLES_TYPE.map((r) => fontPackage(house.fonts[r].family)))]
  return `${HEADER}\n${pkgs.map((p) => `@import '${p}';`).join('\n')}\n`
}

/** The roles on Starlight's variables. Starlight declares its own on
    :root and :root[data-theme='light'], so these match both. */
export function starlightCss(): string {
  return [
    HEADER,
    block(':root, :root[data-theme]', [
      '--sl-font: var(--font-text);',
      '--sl-font-mono: var(--font-mono);',
      '--sl-color-white: var(--text);',
      '--sl-color-gray-1: var(--text);',
      '--sl-color-gray-2: var(--text-muted);',
      '--sl-color-gray-3: var(--text-subtle);',
      '--sl-color-gray-4: oklch(var(--shade-4) var(--tone-base));',
      '--sl-color-gray-5: var(--line);',
      '--sl-color-gray-6: var(--raised);',
      '--sl-color-gray-7: var(--sunk);',
      '--sl-color-black: var(--panel);',
      '--sl-color-bg-nav: var(--ground);',
      '--sl-color-bg-sidebar: var(--ground);',
      '--sl-color-accent-low: var(--accent-soft);',
      '--sl-color-accent: var(--accent-fill);',
      '--sl-color-accent-high: var(--accent-text);',
      '--sl-color-text-accent: var(--accent-text);',
      '--sl-color-text-invert: var(--on-accent);',
      '--sl-color-green: var(--success-text);',
      '--sl-color-green-low: var(--success-soft);',
      '--sl-color-orange: var(--warning-text);',
      '--sl-color-orange-low: var(--warning-soft);',
      '--sl-color-red: var(--error-text);',
      '--sl-color-red-low: var(--error-soft);',
      '--sl-color-blue: var(--info-text);',
      '--sl-color-blue-low: var(--info-soft);',
      '--sl-color-purple: var(--help-text);',
      '--sl-color-purple-low: var(--help-soft);',
    ]),
    '/* Headings in the display face, as the shell sets them. */',
    block(':root :is(h1, h2, h3, h4, h5, h6)', [
      'font-family: var(--font-display);',
      'font-weight: var(--fw-display);',
      'letter-spacing: var(--track-display);',
    ]),
  ].join('\n')
}

/** An icon of icons.json, 256 square, in currentColor. */
export const iconSvg = (body: string): string =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="currentColor" aria-hidden="true">${body}</svg>\n`
